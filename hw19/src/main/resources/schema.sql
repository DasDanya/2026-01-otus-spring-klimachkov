create table if not exists users (
    id bigint generated by default as identity (start with 100 increment by 1) primary key,
    name varchar(255) not null,
    email varchar(254) not null,
    password varchar(255) not null,
    role varchar(30) not null,
    locked boolean not null,

    constraint uq_users_email unique (email),

    -- Проверка доступных ролей
    constraint chk_user_role check (
        role in ('SYSTEM_ADMIN', 'OFFICE_ADMIN', 'EMPLOYEE')
    )
);

create table if not exists refresh_tokens (
    id bigint generated by default as identity primary key,
    token varchar(255) not null,
    user_id bigint not null,

    constraint tokens_user_id_fkey
    foreign key (user_id)
    references users (id)
    on delete cascade
);

create table if not exists employees (
    id bigint generated by default as identity (start with 100 increment by 1) primary key,
    firstname varchar(60) not null,
    lastname varchar(100) not null,
    middlename varchar(60),
    user_id bigint not null,

    constraint uq_employees_user_id unique (user_id),

    constraint employees_user_id_fkey
    foreign key (user_id)
    references users (id)
    on delete cascade
);

create table if not exists locations (
    id bigint generated by default as identity (start with 100 increment by 1) primary key,
    name varchar(100) not null,

    constraint uq_locations_name unique (name)
);

create table if not exists workplaces (
    id bigint generated by default as identity (start with 100 increment by 1) primary key,
    location_id bigint not null,
    name varchar(3) not null,
    type varchar(30) not null,
    capacity smallint not null,
    employee_id bigint,

    constraint uq_workplaces_location_name unique (location_id, name),
    constraint uq_workplaces_employee_id unique (employee_id),

    constraint workplaces_location_id_fkey foreign key (location_id)
    references locations (id)
    on delete cascade,

    constraint workplaces_employee_id_fkey foreign key (employee_id)
    references employees (id),

    -- Проверка доступных типов
    constraint chk_workplaces_type_valid
        check (type in ('INDIVIDUAL', 'HOT_DESK')),

    -- Проверка вместимости в зависимости от типа
    constraint chk_workplaces_capacity_by_type
        check (capacity = 1 and type in ('INDIVIDUAL', 'HOT_DESK')),

    -- Логика привязки сотрудника к рабочему месту (сотрудник обязательно должен быть указан
    -- у индивидуального рабочего места, а у остальных рабочих мест наоборот)
    constraint chk_workplaces_employee_by_type
        check (
            (type = 'INDIVIDUAL' and employee_id is not null) or
            (type <> 'INDIVIDUAL' and employee_id is null)
        )
);

create table if not exists reservations (
    id bigint generated by default as identity (start with 100 increment by 1) primary key,
    workplace_id bigint not null,
    employee_id bigint not null,
    start_time timestamp not null,
    end_time timestamp not null,

    constraint fk_reservations_workplace
    foreign key (workplace_id)
    references workplaces(id)
    on delete cascade,

    constraint fk_reservations_employee
    foreign key (employee_id)
    references employees(id)
    on delete cascade,

    -- Дата окончания должна быть позже даты начала
    constraint chk_reservation_time
    check (end_time > start_time)
);