package ru.klimachkov.workplaces.models;

/**
 * Роли пользователей в системе.
 *
 * <p>Определяет уровень доступа и доступные операции для пользователя.</p>
 *
 * <ul>
 *     <li>{@link #SYSTEM_ADMIN} — полный доступ ко всем функциям системы</li>
 *     <li>{@link #OFFICE_ADMIN} — управление локациями, рабочими местами,
 *     бронированиями и информацией о сотрудниках</li>
 *     <li>{@link #EMPLOYEE} — просмотр бизнес-данных (локации, сотрудники,
 *     рабочие места, бронирования), а также возможность бронирования рабочих мест</li>
 * </ul>
 *
 * @see User
 */
public enum UserRole {
    SYSTEM_ADMIN,
    OFFICE_ADMIN,
    EMPLOYEE
}
