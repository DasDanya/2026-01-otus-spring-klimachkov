create table authors (
    id bigserial,
    full_name varchar(255),
    primary key (id)
);

create table genres (
    id bigserial,
    name varchar(255),
    primary key (id)
);

create table books (
    id bigserial,
    title varchar(255),
    author_id bigint references authors (id) on delete cascade,
    primary key (id)
);

create table books_genres (
    book_id bigint references books(id) on delete cascade,
    genre_id bigint references genres(id) on delete cascade,
    primary key (book_id, genre_id)
);

create table commentaries (
    id bigserial,
    text varchar(255),
    book_id bigint not null references books (id) on delete cascade,
    primary key (id)
);

create table users (
    id bigserial,
    username varchar(255) not null unique,
    password varchar(255) not null,
    primary key (id)
);

create table roles (
    id bigserial,
    name varchar(255) not null unique,
    primary key (id)
);

create table users_roles (
    user_id bigint not null references users(id) on delete cascade,
    role_id bigint not null references roles(id) on delete cascade,
    primary key (user_id, role_id)
);

create sequence acl_sid_seq start with 1 increment by 1;

create table acl_sid (
  id bigint default nextval('acl_sid_seq') not null,
  principal boolean not null,
  sid varchar(100) not null,
  primary key (id),
  constraint unique_uk_acl_sid unique (sid, principal)
);

create sequence acl_class_seq start with 1 increment by 1;

create table acl_class (
  id bigint default nextval('acl_class_seq') not null,
  class varchar(255) not null,
  primary key (id),
  constraint unique_uk_acl_class unique (class)
);

create table acl_object_identity (
  id bigint not null generated by default as identity,
  object_id_class bigint not null,
  object_id_identity bigint not null,
  parent_object bigint,
  owner_sid bigint,
  entries_inheriting boolean not null,
  primary key (id),
  constraint unique_uk_acl_object_identity unique (object_id_class, object_id_identity),
  constraint foreign_fk_aoi_parent_object foreign key (parent_object) references acl_object_identity (id),
  constraint foreign_fk_aoi_object_id_class foreign key (object_id_class) references acl_class (id),
  constraint foreign_fk_aoi_owner_sid foreign key (owner_sid) references acl_sid (id)
);

create table acl_entry (
  id bigint not null generated by default as identity,
  acl_object_identity bigint not null,
  ace_order int not null,
  sid bigint not null,
  mask int not null,
  granting boolean not null,
  audit_success boolean not null,
  audit_failure boolean not null,
  primary key (id),
  constraint unique_uk_acl_entry unique (acl_object_identity, ace_order),
  constraint foreign_fk_ace_acl_object_identity foreign key (acl_object_identity) references acl_object_identity (id),
  constraint foreign_fk_ace_sid foreign key (sid) references acl_sid (id)
);